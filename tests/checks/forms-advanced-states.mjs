import { createRequire } from 'node:module';
import path from 'node:path';
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
import { moduleDemos, moduleScripts, moduleStyles } from '../lib/src-sources.mjs';
import { cacheDir } from '../lib/test-output.mjs';
const require = createRequire(import.meta.url);
const { chromium } = require('../tools/node_modules/playwright-core');
const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..', '..');
const shotDir = cacheDir(root, 'checks', 'forms-advanced');
const MODULES = ['core', 'ui-forms-basic', 'ui-forms-advanced'];
const css = moduleStyles(root, MODULES).map(f=>path.join(root,f));
const js = [...moduleScripts(root, MODULES), ...moduleDemos(root, ['ui-forms-advanced'])].map(f=>path.join(root,f));
const browser = await chromium.launch({ executablePath: 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', headless: true });
const page = await browser.newPage({ viewport: { width: 1100, height: 1300 } });
const errors=[];
page.on('pageerror', e=>errors.push(e.message));
page.on('console', m=>{if(m.type()==='error')errors.push(m.text())});
await page.setContent('<style>html,body{margin:0;padding:0;background:#f4f6f9}</style><div id="host" style="padding:20px"></div>');
for (const f of css) await page.addStyleTag({path:f});
for (const f of js) await page.addScriptTag({path:f});
await page.evaluate(() => {
  const host=document.getElementById('host');
  window.__inst=NoteGalleryDemos['F11'](host);
  const buttons=Array.from(host.querySelectorAll('button'));
  const invalid=buttons.find(b=>b.textContent.indexOf('填入无效值并提交')>=0);
  invalid.click();
});
await page.screenshot({path:path.join(shotDir,'forms-advanced-f11-error.png'),fullPage:true});
await page.evaluate(()=>{window.__inst.destroy();document.getElementById('host').replaceChildren();});
await page.evaluate(() => {
  const host=document.getElementById('host');
  window.__inst=NoteGalleryDemos['F14'](host);
  const buttons=Array.from(host.querySelectorAll('button'));
  buttons.find(b=>b.textContent.indexOf('写入带透明度')>=0).click();
});
await page.screenshot({path:path.join(shotDir,'forms-advanced-f14-invalid.png'),fullPage:true});
await page.evaluate(()=>{window.__inst.destroy();document.getElementById('host').replaceChildren();});
await page.evaluate(() => {
  const host=document.getElementById('host');
  window.__inst=NoteGalleryDemos['F15'](host);
  const buttons=Array.from(host.querySelectorAll('button'));
  buttons.find(b=>b.textContent.indexOf('模拟拖入两个合法文件')>=0).click();
  buttons.find(b=>b.textContent.indexOf('模拟拖入超限文件')>=0).click();
  buttons.find(b=>b.textContent.indexOf('模拟拖入类型不符')>=0).click();
});
await page.screenshot({path:path.join(shotDir,'forms-advanced-f15-errors.png'),fullPage:true});
await page.evaluate(()=>{window.__inst.destroy();document.getElementById('host').replaceChildren();});
await browser.close();
console.log(JSON.stringify({errors}));
if(errors.length) process.exit(1);
