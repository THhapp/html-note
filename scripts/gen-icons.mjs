#!/usr/bin/env node
/* Generate src/core/icons-data.js from vendor/lucide/icons/*.svg.
   Usage: node scripts/gen-icons.mjs [--check]
   The output is deterministic and contains shape data only; runtime SVG
   construction lives in src/core/icons.js. */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(scriptDir, '..');
const iconsDir = path.join(projectRoot, 'vendor', 'lucide', 'icons');
const outputFile = path.join(projectRoot, 'src', 'core', 'icons-data.js');
const checkOnly = process.argv.includes('--check');

const ALLOWED_TAGS = new Set(['circle', 'ellipse', 'line', 'path', 'polygon', 'polyline', 'rect']);
const ALLOWED_CHILD_ATTRIBUTES = new Set([
  'cx', 'cy', 'd', 'height', 'points', 'r', 'rx', 'ry',
  'width', 'x', 'x1', 'x2', 'y', 'y1', 'y2'
]);
const ALLOWED_ROOT_ATTRIBUTES = new Set([
  'class', 'fill', 'height', 'stroke', 'stroke-linecap', 'stroke-linejoin',
  'stroke-width', 'viewBox', 'width', 'xmlns'
]);

const ATTRIBUTE_RE = /([A-Za-z_:][A-Za-z0-9_.:-]*)="([^"]*)"/g;

function fail(message) {
  throw new Error(`[icons] ${message}`);
}

function parseAttributes(raw, allowed, context) {
  const attributes = {};
  const leftovers = raw.replace(ATTRIBUTE_RE, (_match, name, value) => {
    if (!allowed.has(name)) fail(`${context}: unsupported attribute "${name}"`);
    if (value.includes('&') || value.includes('<') || value.includes('>')) {
      fail(`${context}: unsafe entity or markup in attribute "${name}"`);
    }
    if (Object.prototype.hasOwnProperty.call(attributes, name)) {
      fail(`${context}: duplicate attribute "${name}"`);
    }
    attributes[name] = value;
    return '';
  });
  if (leftovers.replace(/\/\s*$/, '').trim() !== '') {
    fail(`${context}: malformed attributes near "${leftovers.trim()}"`);
  }
  return attributes;
}

function parseSvg(source, name) {
  const context = `${name}.svg`;
  const svgMatch = /<svg\b([^>]*)>([\s\S]*?)<\/svg\s*>/i.exec(source);
  if (!svgMatch) fail(`${context}: missing <svg> root`);

  const rootAttributes = parseAttributes(svgMatch[1], ALLOWED_ROOT_ATTRIBUTES, context);
  const viewBox = rootAttributes.viewBox;
  if (!viewBox) fail(`${context}: missing viewBox`);
  if (rootAttributes.fill != null && rootAttributes.fill !== 'none') {
    fail(`${context}: expected fill="none"`);
  }
  if (rootAttributes.stroke != null && rootAttributes.stroke !== 'currentColor') {
    fail(`${context}: expected stroke="currentColor"`);
  }
  const strokeWidth = rootAttributes['stroke-width'] || '2';

  const bodyParts = [];
  let bodyRest = svgMatch[2];
  let tagMatch;
  const tagRe = /<([A-Za-z][A-Za-z0-9:-]*)\b([^>]*)>/g;
  while ((tagMatch = tagRe.exec(svgMatch[2])) !== null) {
    const tag = tagMatch[1];
    if (!ALLOWED_TAGS.has(tag)) fail(`${context}: unsupported element <${tag}>`);
    const rawAttributes = tagMatch[2];
    if (!/\/\s*$/.test(rawAttributes)) {
      fail(`${context}: <${tag}> must be self-closing`);
    }
    const attributes = parseAttributes(rawAttributes, ALLOWED_CHILD_ATTRIBUTES, `${context} <${tag}>`);
    const orderedAttributes = {};
    Object.keys(attributes).sort().forEach((key) => {
      orderedAttributes[key] = attributes[key];
    });
    bodyParts.push({ tag, attrs: orderedAttributes });
    bodyRest = bodyRest.replace(tagMatch[0], '');
  }
  if (bodyRest.replace(/\s+/g, '') !== '') {
    fail(`${context}: unsupported content inside <svg>`);
  }
  if (!bodyParts.length) fail(`${context}: no drawable shape`);

  return {
    viewBox,
    strokeWidth,
    children: bodyParts
  };
}

if (!fs.existsSync(iconsDir)) fail(`missing icon directory: ${iconsDir}`);

const files = fs.readdirSync(iconsDir)
  .filter((file) => file.endsWith('.svg'))
  .sort();

if (!files.length) fail('no SVG icons found');
if (new Set(files.map((file) => file.toLowerCase())).size !== files.length) {
  fail('duplicate icon file names (case-insensitive)');
}

const icons = {};
for (const file of files) {
  const name = file.slice(0, -4);
  if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(name)) fail(`invalid icon name: ${name}`);
  if (Object.prototype.hasOwnProperty.call(icons, name)) fail(`duplicate icon name: ${name}`);
  const source = fs.readFileSync(path.join(iconsDir, file), 'utf8');
  icons[name] = parseSvg(source, name);
}

const sortedIcons = {};
Object.keys(icons).sort().forEach((name) => {
  sortedIcons[name] = icons[name];
});

const serialized = JSON.stringify(sortedIcons, null, 2);
const banner = [
  '/* Generated by scripts/gen-icons.mjs from vendor/lucide/icons/*.svg. Do not edit. */',
  '/*! Lucide static icons v1.62.0, ISC license; see vendor/lucide/LICENSE. */',
  '/* Pure data; runtime SVG construction is in icons.js. */',
  '(function (global) {',
  "  'use strict';",
  '  var NoteCore = global.NoteCore = global.NoteCore || {};',
  '  NoteCore.iconData = ' + serialized.split('\n').join('\n  ') + ';',
  '})(window);',
  ''
].join('\n');

if (checkOnly) {
  if (!fs.existsSync(outputFile)) {
    console.error('[icons] icons-data.js is missing; run node scripts/gen-icons.mjs');
    process.exitCode = 1;
  } else {
    const current = fs.readFileSync(outputFile, 'utf8').replace(/\r\n/g, '\n');
    if (current !== banner) {
      console.error('[icons] icons-data.js is out of date; run node scripts/gen-icons.mjs');
      process.exitCode = 1;
    } else {
      console.log(`[icons] up to date (${files.length} icons)`);
    }
  }
} else {
  fs.mkdirSync(path.dirname(outputFile), { recursive: true });
  fs.writeFileSync(outputFile, banner, 'utf8');
  console.log(`[icons] generated ${files.length} icons -> ${path.relative(projectRoot, outputFile)}`);
}
